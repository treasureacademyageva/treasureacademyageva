#!/usr/bin/env python3
"""Bundle reviewed static News pages as gate-off server fallbacks.

Vercel sends News through the CMS delivery function so published revisions can
replace these exact routes without a deployment. While the CMS gate is closed,
empty or missing, the byte-for-byte reviewed static News journey remains live.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROUTES = json.loads((ROOT / "config" / "public-routes.json").read_text(encoding="utf-8"))["routes"]
news = {
    item["canonical"]: (ROOT / item["source"].lstrip("/")).read_text(encoding="utf-8")
    for item in ROUTES
    if item["canonical"] == "/news" or item["canonical"].startswith("/news/")
}
out = ROOT / "server" / "public-fallbacks.generated.mjs"
out.write_text(
    "// Generated by tools/build-public-fallbacks.py; do not edit by hand.\n"
    f"export const PUBLIC_HTML_FALLBACKS = Object.freeze({json.dumps(news, ensure_ascii=False, separators=(',', ':'))});\n",
    encoding="utf-8",
)
print(f"Bundled {len(news)} reviewed static News fallbacks in {out.relative_to(ROOT)}")
