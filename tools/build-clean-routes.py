#!/usr/bin/env python3
"""Generate the clean-route cutover artifacts from one reviewed route registry.

The filesystem keeps its stable .html build inputs. Public canonicals, internal
links, Vercel one-hop redirects/rewrites, local discovery data and the fixed
sitemap projection use clean paths. Run after all page generators and before
the held-content manifest so candidate hashes describe the final output.
"""
from __future__ import annotations

import html
import json
import posixpath
import re
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

ROOT = Path(__file__).resolve().parents[1]
REGISTRY_PATH = ROOT / "config" / "public-routes.json"
SITE = "https://www.treasureacademyageva.com"
ATTR_RE = re.compile(r"(?P<name>href|action)=(?P<quote>['\"])(?P<value>.*?)(?P=quote)", re.I)


def load_registry() -> tuple[dict, dict[str, str]]:
    data = json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
    if data.get("version") != 1 or data.get("siteOrigin") != SITE:
        raise SystemExit("Unsupported public-route registry")
    routes = data.get("routes")
    if not isinstance(routes, list) or not routes:
        raise SystemExit("Public-route registry is empty")
    sources: set[str] = set()
    canonicals: set[str] = set()
    mapping: dict[str, str] = {}
    for row in routes:
        source = str(row.get("source") or "")
        canonical = str(row.get("canonical") or "")
        if not re.fullmatch(r"/(?:[a-z0-9-]+/)*[a-z0-9-]+\.html", source):
            raise SystemExit(f"Unsafe route source: {source}")
        if canonical != "/" and not re.fullmatch(r"/(?:[a-z0-9-]+/)*[a-z0-9-]+", canonical):
            raise SystemExit(f"Unsafe canonical path: {canonical}")
        if source in sources or canonical in canonicals:
            raise SystemExit(f"Duplicate route mapping: {source} -> {canonical}")
        if not (ROOT / source.lstrip("/")).is_file():
            raise SystemExit(f"Missing route source file: {source}")
        sources.add(source)
        canonicals.add(canonical)
        mapping[source] = canonical
    return data, mapping


def clean_url(value: str, current_source: str, mapping: dict[str, str]) -> str:
    if not value or value.startswith(("#", "mailto:", "tel:", "javascript:", "data:")):
        return value
    decoded = html.unescape(value)
    parsed = urlsplit(decoded)
    if parsed.scheme or parsed.netloc:
        if f"{parsed.scheme}://{parsed.netloc}" != SITE:
            return value
        path = parsed.path
        replacement = mapping.get(path)
        return urlunsplit((parsed.scheme, parsed.netloc, replacement, parsed.query, parsed.fragment)) if replacement else value
    if parsed.path.startswith("/"):
        source = parsed.path
    else:
        source = "/" + posixpath.normpath(posixpath.join(posixpath.dirname(current_source.lstrip("/")), parsed.path))
    replacement = mapping.get(source)
    if not replacement:
        return value
    return urlunsplit(("", "", replacement, parsed.query, parsed.fragment))


def rewrite_html(data: dict, mapping: dict[str, str]) -> int:
    changed = 0
    route_files = {ROOT / row["source"].lstrip("/") for row in data["routes"]}
    supporting_files = set(ROOT.glob("*.html")) | set((ROOT / "classes").glob("*.html")) | set((ROOT / "news").glob("*.html")) | set((ROOT / "portal").glob("*.html"))
    for path in sorted(route_files | supporting_files):
        source = "/" + path.relative_to(ROOT).as_posix()
        text = path.read_text(encoding="utf-8")
        updated = text
        for old, new in mapping.items():
            updated = updated.replace(SITE + old, SITE + new)

        def replace_attr(match: re.Match[str]) -> str:
            value = clean_url(match.group("value"), source, mapping)
            return f"{match.group('name')}={match.group('quote')}{value}{match.group('quote')}"

        updated = ATTR_RE.sub(replace_attr, updated)
        if updated != text:
            path.write_text(updated, encoding="utf-8")
            changed += 1
    return changed


def rewrite_discovery(mapping: dict[str, str]) -> None:
    search_path = ROOT / "assets" / "js" / "search-index.js"
    text = search_path.read_text(encoding="utf-8")
    prefix = "window.TA_SEARCH_INDEX="
    start = text.index(prefix) + len(prefix)
    end = text.rindex(";")
    rows = json.loads(text[start:end])
    for row in rows:
        value = str(row.get("u") or "")
        row["u"] = clean_url(value, "/index.html", mapping)
    search_path.write_text(
        "/* Generated by tools/build-search-index.py and clean-routed by tools/build-clean-routes.py. */\n"
        + prefix + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )

    kb_path = ROOT / "assets" / "data" / "kb.json"
    kb = json.loads(kb_path.read_text(encoding="utf-8"))
    for row in kb.get("docs", []):
        if "url" in row:
            row["url"] = clean_url(str(row["url"]), "/index.html", mapping)
    kb_path.write_text(json.dumps(kb, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")


def write_generated_module(data: dict) -> None:
    routes = data["routes"]
    fixed = [
        {key: row[key] for key in ("canonical", "lastmod", "changefreq", "priority")}
        for row in routes if row.get("indexable") is True
    ]
    output = (
        "/* Generated by tools/build-clean-routes.py. Do not edit directly. */\n"
        f"export const STATIC_ROUTE_REGISTRY = Object.freeze({json.dumps(routes, ensure_ascii=False, separators=(',', ':'))});\n"
        f"export const FIXED_SITEMAP_ROUTES = Object.freeze({json.dumps(fixed, ensure_ascii=False, separators=(',', ':'))});\n"
    )
    path = ROOT / "server" / "public-routes.generated.mjs"
    path.write_text(output, encoding="utf-8")


def write_static_sitemap(data: dict) -> None:
    rows = []
    for row in data["routes"]:
        if row.get("indexable") is not True:
            continue
        rows.append(
            "  <url>\n"
            f"    <loc>{SITE}{row['canonical']}</loc>\n"
            f"    <lastmod>{row['lastmod']}</lastmod>\n"
            f"    <changefreq>{row['changefreq']}</changefreq>\n"
            f"    <priority>{float(row['priority']):.1f}</priority>\n"
            "  </url>"
        )
    xml = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "\n".join(rows) + "\n</urlset>\n"
    )
    (ROOT / "sitemap.xml").write_text(xml, encoding="utf-8")


def update_vercel(data: dict, mapping: dict[str, str]) -> None:
    path = ROOT / "vercel.json"
    config = json.loads(path.read_text(encoding="utf-8"))
    generated_sources = set(mapping) | {"/class", "/explore", "/classes/creche", "/classes/creche.html"}
    redirects = [row for row in config.get("redirects", []) if row.get("source") not in generated_sources]
    host = [row for row in redirects if row.get("has")]
    legacy = [row for row in redirects if not row.get("has")]
    generated = [
        {"source": source, "destination": canonical, "permanent": True}
        for source, canonical in mapping.items()
    ]
    generated += [
        {"source": "/class", "destination": "/classes", "permanent": True},
        {"source": "/explore", "destination": "/site-map", "permanent": True},
        {"source": "/classes/creche", "destination": "/classes/pre-nursery", "permanent": True},
        {"source": "/classes/creche.html", "destination": "/classes/pre-nursery", "permanent": True},
    ]
    config["redirects"] = host + generated + legacy

    clean_sources = set(mapping.values()) - {"/"}
    clean_sources.update({"/sitemap.xml", "/classes/creche"})
    rewrites = [row for row in config.get("rewrites", []) if row.get("source") not in clean_sources]
    split = next((i for i, row in enumerate(rewrites) if row.get("source") == "/news/feed.xml"), len(rewrites))
    static_rewrites = [
        {"source": "/sitemap.xml", "destination": "/api/public-content?route=sitemap"},
        {"source": "/news", "destination": "/api/public-content?route=news-list"},
    ]
    for source, canonical in mapping.items():
        if canonical == "/" or canonical == "/news" or canonical.startswith("/news/"):
            continue
        static_rewrites.append({"source": canonical, "destination": source})
    config["rewrites"] = rewrites[:split] + static_rewrites + rewrites[split:]

    header_sources = set(mapping.values()) - {"/"}
    headers = [row for row in config.get("headers", []) if row.get("source") not in header_sources]
    generated_headers = []
    for row in data["routes"]:
        canonical = row["canonical"]
        if canonical == "/" or canonical == "/news" or canonical.startswith("/news/"):
            continue
        values = [{"key": "Cache-Control", "value": "no-cache"}]
        if row.get("indexable") is not True:
            values.append({"key": "X-Robots-Tag", "value": "noindex, follow"})
        generated_headers.append({"source": canonical, "headers": values})
    config["headers"] = headers + generated_headers
    path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    data, mapping = load_registry()
    changed = rewrite_html(data, mapping)
    rewrite_discovery(mapping)
    write_generated_module(data)
    write_static_sitemap(data)
    update_vercel(data, mapping)
    print(f"Clean-route registry applied: {len(mapping)} routes, {changed} page files updated, {sum(1 for r in data['routes'] if r['indexable'])} fixed sitemap URLs.")


if __name__ == "__main__":
    main()
