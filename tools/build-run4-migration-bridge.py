#!/usr/bin/env python3
"""Build the fail-closed Run 4 Supabase migration-control workspace.

The production ledger predates CLI-aligned repository filenames. This builder
creates historical *ledger markers* with the exact remote versions, followed by
byte-for-byte copies of pending migrations 009 and 010. Historical markers
raise an exception if a wrong project ever attempts to apply them.

This workspace is ONLY for linked production migration list/dry-run/push. It is
never a local reset, seed, pull, diff, include-all, or general schema source.
"""

from __future__ import annotations

import hashlib
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "supabase/release/20261025_RUN4_PRODUCTION_MIGRATION_LEDGER.json"
WORKSPACE = ROOT / "supabase/release/run-04-cli-workspace"
MIGRATIONS = WORKSPACE / "supabase/migrations"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    remote = manifest["remote_history"]
    pending = manifest["pending"]

    remote_versions = [row["version"] for row in remote]
    pending_versions = [row["version"] for row in pending]
    if remote_versions != sorted(remote_versions) or len(set(remote_versions)) != len(remote_versions):
        raise SystemExit("Remote ledger versions are not unique and strictly ordered")
    if pending_versions != sorted(pending_versions) or len(set(pending_versions)) != len(pending_versions):
        raise SystemExit("Pending versions are not unique and strictly ordered")
    if set(remote_versions) & set(pending_versions) or min(pending_versions) <= max(remote_versions):
        raise SystemExit("Pending versions do not follow the complete remote ledger")
    if pending_versions != ["20261025000100", "20261025000200"]:
        raise SystemExit("Run 4 bridge permits only migrations 009 and 010")

    for row in remote:
        source_name = row.get("source", "")
        source_hash = row.get("source_sha256")
        if source_hash:
            source = ROOT / source_name
            if not source.is_file() or sha256(source) != source_hash:
                raise SystemExit(f"Applied source identity mismatch: {source_name}")
            if row.get("verification") == "remote_sql_equals_local_without_final_newline":
                local_md5 = hashlib.md5(source.read_bytes().rstrip(b"\n")).hexdigest()
                if local_md5 != row["sql_md5"]:
                    raise SystemExit(f"Remote/local statement mismatch: {source_name}")

    if MIGRATIONS.exists():
        shutil.rmtree(MIGRATIONS)
    MIGRATIONS.mkdir(parents=True)

    for row in remote:
        filename = f"{row['version']}_{row['name']}.sql"
        source_detail = row.get("source", "remote production history only")
        source_hash = row.get("source_sha256", "not available in the canonical migration folder")
        marker = f"""-- RUN 4 PRODUCTION LEDGER MARKER — ALREADY APPLIED; NEVER EXECUTE.
-- Production project: {manifest['project_ref']}
-- Remote migration: {row['version']} / {row['name']}
-- Remote statement count: {row['statement_count']}
-- Remote SQL character count: {row['sql_chars']}
-- Remote SQL MD5: {row['sql_md5']}
-- Reviewed source: {source_detail}
-- Reviewed source SHA-256: {source_hash}
--
-- The version exists only so Supabase CLI can compare the canonical remote
-- ledger before applying migrations 009 and 010. If this version is absent on
-- the selected target, fail closed instead of replaying historical SQL.

do $run4_historical_migration_guard$
begin
  raise exception 'Run 4 historical ledger marker {row['version']} must never be applied';
end
$run4_historical_migration_guard$;
"""
        (MIGRATIONS / filename).write_text(marker, encoding="utf-8")

    for row in pending:
        source = ROOT / row["source"]
        if not source.is_file() or sha256(source) != row["source_sha256"]:
            raise SystemExit(f"Pending source identity mismatch: {row['source']}")
        shutil.copyfile(source, MIGRATIONS / source.name)

    (WORKSPACE / "supabase/config.toml").write_text(
        f'project_id = "{manifest["project_ref"]}"\n\n[db.migrations]\nenabled = true\n',
        encoding="utf-8",
    )
    (WORKSPACE / "README.md").write_text(
        """# Run 4 production migration-control workspace

Generated by `tools/build-run4-migration-bridge.py` from the reviewed production
ledger manifest. Historical files are fail-closed ledger markers and migrations
009/010 are byte-for-byte copies of the canonical reviewed files.

Permitted commands after explicit production-window approval:

```text
supabase --workdir supabase/release/run-04-cli-workspace migration list --linked
supabase --workdir supabase/release/run-04-cli-workspace db push --linked --dry-run
supabase --workdir supabase/release/run-04-cli-workspace db push --linked
```

The dry run must list exactly migrations 009 and 010. Never use this workspace
with `db reset`, `db pull`, `db diff`, seeds, `--include-all`, history repair or
a project other than the recorded production project. Historical marker SQL
raises an exception if a mismatched target tries to apply it.
""",
        encoding="utf-8",
    )

    generated = sorted(MIGRATIONS.glob("*.sql"))
    if len(generated) != len(remote) + len(pending):
        raise SystemExit("Generated migration count mismatch")
    print(
        f"RUN 4 MIGRATION BRIDGE: {len(remote)} applied ledger markers + "
        f"{len(pending)} exact pending migrations generated."
    )


if __name__ == "__main__":
    main()
