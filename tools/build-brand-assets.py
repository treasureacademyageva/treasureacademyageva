#!/usr/bin/env python3
"""Validate owner-supplied brand assets and expose safe readiness metadata."""
from __future__ import annotations

import json
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets" / "data" / "brand-assets.json"
OUTPUT = ROOT / "assets" / "js" / "brand-assets.js"

data = json.loads(SOURCE.read_text(encoding="utf-8"))
if data.get("schema") != "treasure-brand-assets-v1":
    raise SystemExit("Unsupported brand asset schema")

errors: list[str] = []
logo = data.get("identity", {}).get("logo", {})
if logo.get("status") == "verified":
    src = str(logo.get("src", ""))
    if not src or not (ROOT / src.lstrip("/")).is_file() or not logo.get("authority") or not logo.get("reviewDate"):
        errors.append("identity.logo: verified logo needs an existing file, authority and reviewDate")
for key, image in data.get("images", {}).items():
    if image.get("status") != "verified":
        continue
    required = ("src", "width", "height", "alt", "authority", "reviewDate")
    missing = [field for field in required if not image.get(field)]
    if missing:
        errors.append(f"{key}: verified image missing {', '.join(missing)}")
    src = str(image.get("src", ""))
    if src.startswith("/") and not (ROOT / src.lstrip("/")).is_file():
        errors.append(f"{key}: source file does not exist: {src}")
    if not image.get("consentConfirmed"):
        errors.append(f"{key}: consentConfirmed must be true before verified publication")
    if not image.get("placements"):
        errors.append(f"{key}: at least one approved placement is required")

for index, profile in enumerate(data.get("socialProfiles", []), start=1):
    if profile.get("status") != "verified":
        continue
    url = str(profile.get("url", ""))
    if urlparse(url).scheme != "https" or not profile.get("authority") or not profile.get("reviewDate"):
        errors.append(f"socialProfiles[{index}]: verified profile needs HTTPS URL, authority and reviewDate")

for index, document in enumerate(data.get("publicDocuments", []), start=1):
    if document.get("status") != "verified":
        continue
    src = str(document.get("src", ""))
    if not src or not (ROOT / src.lstrip("/")).is_file() or not document.get("reviewDate") or not document.get("owner"):
        errors.append(f"publicDocuments[{index}]: verified document needs an existing file, owner and reviewDate")

if errors:
    raise SystemExit("Brand asset validation failed:\n- " + "\n- ".join(errors))

safe = {
    "schema": data["schema"],
    "updated": data.get("updated"),
    "identity": data.get("identity", {}),
    "images": data.get("images", {}),
    "socialProfiles": data.get("socialProfiles", []),
    "publicDocuments": data.get("publicDocuments", []),
    "readiness": {
        "verifiedLogo": logo.get("status") == "verified",
        "verifiedImages": sum(item.get("status") == "verified" for item in data.get("images", {}).values()),
        "verifiedProfiles": sum(item.get("status") == "verified" for item in data.get("socialProfiles", [])),
        "verifiedDocuments": sum(item.get("status") == "verified" for item in data.get("publicDocuments", [])),
    },
}
OUTPUT.write_text(
    "/* Generated by tools/build-brand-assets.py; owner-approved metadata only. */\n"
    "window.TA_BRAND_ASSETS=" + json.dumps(safe, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
print("Validated brand asset registry: " + ", ".join(f"{key}={value}" for key, value in safe["readiness"].items()))
