#!/usr/bin/env python3
"""Build non-sensitive page-level clarity metrics for the private operations page."""
from __future__ import annotations

import json
import re
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "assets" / "js" / "content-quality.js"
EXCLUDE_PREFIX = "developer"
VAGUE = {"click here", "here", "more", "read more", "learn more", "continue"}


class PageParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.skip = 0
        self.in_main = 0
        self.current: tuple[str, list[str]] | None = None
        self.blocks: list[tuple[str, str]] = []
        self.links: list[str] = []
        self.forms = 0
        self.labels = 0

    def handle_starttag(self, tag: str, attrs) -> None:
        if tag in {"script", "style", "nav", "footer"}:
            self.skip += 1
        if tag == "main":
            self.in_main += 1
        if self.skip or not self.in_main:
            return
        if tag in {"h1", "h2", "h3", "p", "li", "a"}:
            self.current = (tag, [])
        if tag == "form":
            self.forms += 1
        if tag == "label":
            self.labels += 1

    def handle_data(self, data: str) -> None:
        if not self.skip and self.in_main and self.current:
            self.current[1].append(data)

    def handle_endtag(self, tag: str) -> None:
        if self.current and tag == self.current[0]:
            text = " ".join("".join(self.current[1]).split())
            if text:
                if tag == "a":
                    self.links.append(text)
                else:
                    self.blocks.append((tag, text))
            self.current = None
        if tag == "main" and self.in_main:
            self.in_main -= 1
        if tag in {"script", "style", "nav", "footer"} and self.skip:
            self.skip -= 1


def title_for(text: str, fallback: str) -> str:
    match = re.search(r"<h1\b[^>]*>(.*?)</h1>", text, flags=re.I | re.S)
    if not match:
        return fallback
    return " ".join(re.sub(r"<[^>]+>", " ", match.group(1)).split())


pages = sorted(list(ROOT.glob("*.html")) + list((ROOT / "classes").glob("*.html")) + list((ROOT / "news").glob("*.html")))
rows = []
for page in pages:
    rel = page.relative_to(ROOT).as_posix()
    if page.name.startswith(EXCLUDE_PREFIX):
        continue
    source = page.read_text(encoding="utf-8", errors="ignore")
    parser = PageParser()
    parser.feed(source)
    blocks = [(tag, text, len(text.split())) for tag, text in parser.blocks]
    prose = [count for tag, _, count in blocks if tag in {"p", "li"}]
    headings = [text for tag, text, _ in blocks if tag in {"h1", "h2", "h3"}]
    vague = [label for label in parser.links if label.strip().lower() in VAGUE]
    long_count = sum(1 for count in prose if count > 65)
    issues = []
    if not re.search(r"<h1\b", source, flags=re.I): issues.append("missing_h1")
    if long_count: issues.append("long_block")
    if vague: issues.append("vague_link")
    if parser.forms and not parser.labels: issues.append("unlabelled_form")
    rows.append({
        "page": rel,
        "title": title_for(source, page.stem.replace("-", " ").title()),
        "words": sum(count for tag, _, count in blocks if tag in {"p", "li"}),
        "sections": sum(1 for tag, _, _ in blocks if tag == "h2"),
        "longest": max(prose, default=0),
        "longBlocks": long_count,
        "vagueLinks": len(vague),
        "forms": parser.forms,
        "labels": parser.labels,
        "issues": issues,
    })

report = {
    "version": 1,
    "pageCount": len(rows),
    "limits": {"maxBlockWords": 65},
    "totals": {
        "words": sum(row["words"] for row in rows),
        "longBlocks": sum(row["longBlocks"] for row in rows),
        "vagueLinks": sum(row["vagueLinks"] for row in rows),
        "pagesWithIssues": sum(bool(row["issues"]) for row in rows),
    },
    "pages": rows,
}
OUTPUT.write_text(
    "/* Generated by tools/build-content-quality-report.py; metrics only, no page text. */\n"
    "window.TA_CONTENT_QUALITY=" + json.dumps(report, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
print(f"Wrote clarity metrics for {len(rows)} public pages.")
